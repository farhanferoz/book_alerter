# Amazon UK is fronted by aggressive bot-protection that defeats any client
# that doesn't render JS in a real browser (verified 2026-05-14: headless
# Chromium + stealth flags + cookie warm-up still got served the
# "To discuss automated access to Amazon" interstitial). So this source
# drives headless Chromium via Playwright, through a `BrowserSession`
# (sources/browser.py) that the scheduler opens once per run via
# `prepare()`/`cleanup()` and shares across every item's fetch — see
# `BrowserSession`'s docstring for why a persistent profile also fixes a
# data-accuracy bug (first-order promo shipping prices), not just blocking.
#
# Strategy: render BOTH /dp/<ISBN> and /gp/offer-listing/<ISBN>?condition=all
# on every fetch and merge. The dp buy-box almost always also appears as a
# row on the offer-listing page, so a merge-with-dedup gives us the union:
# the new buy-box guaranteed (even on books with a marketplace-empty AOD
# page) plus every used grade Amazon publishes on the marketplace.
#
# Region: UK only at MVP. Pass region="UK" or accept the default.
#
# DOM contract:
#   dp page          - buy-box price under #corePriceDisplay_desktop_feature_div
#                      OR #corePrice_feature_div. Within, .a-price wraps the
#                      number; .a-offscreen carries the screen-reader-friendly
#                      full price ("£7.99"). Prefer .a-offscreen — it's the
#                      most stable selector.
#   offer-listing    - rows under #aod-offer-list, each `#aod-offer` (modern
#                      AOD layout). Legacy fallback: `.olpOffer`. Within each
#                      row: #aod-offer-price (.a-offscreen), #aod-offer-shipping,
#                      #aod-offer-heading (h5 text with the condition),
#                      #aod-offer-soldBy (seller link text).

# Tolerates "£7.99" / "&pound;7.99" / "7.99" — whichever DOM branch we end
# up reading.
_PRICE_NUMERIC_RE = re.compile(r"(\d+(?:\.\d{1,2})?)")

# Fallback path for the dp buy-box price. Amazon's inline JS state embeds
# the current selling price as `"priceAmount":34.52` somewhere in the
# HTML body, ahead of any "lowest used/new from £X" sub-prices. selectolax
# CSS scraping of `.a-price .a-offscreen` is unreliable on this page —
# Amazon's React hydration moves the actual buy-box element around between
# initial render and post-hydration, so the static HTML selectolax sees
# doesn't always contain the visible buy-box price under the expected
# corePriceDisplay scope. The priceAmount field is generated by Amazon's
# pricing service and reflects the same number rendered to the user.
_PRICE_AMOUNT_RE = re.compile(r'"priceAmount"\s*:\s*(\d+(?:\.\d{1,2})?)')

# Amazon UK indexes books by ISBN-10 (which IS the ASIN for books). The /dp
# and /gp/offer-listing URLs only resolve to a real product page when the path
# segment is the ISBN-10. /dp/{ISBN-13} silently serves a generic ~2 KB "Page
# Not Found" instead of redirecting — the page still contains Amazon's
# standard footer copy ("To discuss automated access ..."), which used to
# trip the bot-marker check below.
#
# ISBN-13s starting with 978 map back to a unique ISBN-10. The newer 979
# prefix (post-2007) has no ISBN-10 form; for those we fall back to the
# ISBN-13 URL and accept that books in that narrow range may not resolve.

# Markers that indicate a real anti-bot interstitial (NOT the generic
# footer copy that appears on 404 pages). `validateCaptcha` is the form
# action on Amazon's actual captcha challenge; "Type the characters you
# see" is the captcha prompt; `<title>Robot Check</title>` is the dedicated
# challenge page title.
BOT_MARKERS: tuple[str, ...] = (
    "Type the characters you see",
    "<title>Robot Check</title>",
    "validateCaptcha",
)

# Positive selectors that confirm we're actually looking at the expected
# Amazon UK page layout. Used by the parsers to distinguish "we parsed the
# page and there really are no offers" from "Amazon served something we
# don't recognise" — the latter must raise rather than silently report 0,
# otherwise a new anti-bot variant (one whose substring isn't in BOT_MARKERS)
# would look like a successful empty fetch.
#
# `#dp-container` and `#productTitle` together cover every dp-page variant
# we've captured: the real-capture fixture, the synthetic dp/no-price
# variant (productTitle present), and the synthetic delivery-block fixtures
# (productTitle stripped, dp-container retained).
_DP_PAGE_MARKERS: tuple[str, ...] = ("#dp-container", "#productTitle")
# AOD is the modern offer-listing layout; OLP is the legacy fallback. Both
# fixtures + real captures use the `aod-container` / `aod-offer-list` IDs.
_OFFER_LISTING_PAGE_MARKERS: tuple[str, ...] = (
    "#aod-container",
    "#aod-offer-list",
    "#olpOfferList",
    "#olpProductInformation",
)
# T4.2: a currently-unavailable product's offer-listing request doesn't
# render an AOD container at all — Amazon serves the dp-shaped "currently
# unavailable" page instead (verified on a real capture,
# tests/fixtures/amazon/products/B0GX54WT36-uk-aod-2026-09-04.html: no
# #aod-container/#aod-offer-list, but #outOfStockBuyBox_feature_div=1, and
# its own canonical link matches the ASIN that was requested — a genuine
# "nothing to list" response, not Amazon serving the wrong page). Kept as
# its own narrow marker rather than folding into _DP_PAGE_MARKERS: a bare
# dp-page match would also swallow the F26 wrong-variant-redirect case
# (tests/fixtures/amazon/products/B0CYT8WL1G-uk-aod-2026-09-04.html is
# ALSO dp-shaped, but its canonical points at a different ASIN entirely —
# that one must stay an error, caught upstream by _render_amazon_page's
# canonical-ASIN check, not be silently reinterpreted as "empty" here).
_UNAVAILABLE_PAGE_MARKERS: tuple[str, ...] = ("#outOfStockBuyBox_feature_div",)


def _matches_any_selector(tree: HTMLParser, selectors: tuple[str, ...]) -> bool:
    return any(tree.css_first(sel) is not None for sel in selectors)


# F26 (2026-09-04): Amazon occasionally serves a normal, fully-formed page
# for the WRONG product — reproduced twice against real captures, e.g.
# `/gp/offer-listing/B0CYT8WL1G?condition=all` returning a page whose own
# `<link rel="canonical">` pointed at `B0DLSB1WWK`, an entirely different
# ASIN. `BOT_MARKERS` is structurally unable to catch this: the returned
# HTML has no error markup at all, it's just about the wrong item — so a
# scrape can silently attribute another product's prices to the one being
# tracked.
#
# The check below works for BOTH dp and offer-listing requests uniformly:
# every real capture on file canonicalises to `/dp/<ASIN>` regardless of
# which URL was requested (verified across all four `tests/fixtures/
# amazon/products/*.html` captures AND the live offer-listing capture
# `9780241638194-uk-offer-listing-live-2026-05-23.html`) — including a
# GENUINELY correct, empty offer-listing response (the Echo Dot AOD page,
# 0 third-party rows, canonicalises to its own correct ASIN same as any dp
# response would). So "canonical says /dp/" is not itself a failure signal
# — only a canonical ASIN that disagrees with the one requested is.
#
# `rel` is assumed to precede `href` in the tag, matching every real
# capture on file; not verified against a reversed-attribute-order variant
# because none has been observed.
_CANONICAL_LINK_RE = re.compile(
    r'<link\b[^>]*\brel=["\']canonical["\'][^>]*\bhref=["\']([^"\']+)["\']',
    re.IGNORECASE,
)

# Extracts the ASIN this module itself embedded when building `url` — either
# `dp_url()`'s `/dp/<asin>` or `_offer_listing_url_for_asin()`'s
# `/gp/offer-listing/<asin>?condition=all`. Deliberately NOT
# `normalizers.to_asin`: that helper's path allowlist (dp / gp/product /
# gp/aw/d / exec/obidos/asin / product / d) doesn't include
# `gp/offer-listing` — it's scoped to Amazon's own canonical-ish URL forms
# a user might paste in, not the request URLs this scraper constructs — so
# reusing it here would silently skip the check for every offer-listing
# request, exactly the case F26 needs covered. Widening `to_asin` itself
# was ruled out: it's shared by other callers with no reason to accept
# offer-listing paths.
_REQUESTED_URL_ASIN_RE = re.compile(
    r"/(?:dp|gp/offer-listing)/([A-Z0-9]{10})(?:[/?]|$)",
    re.IGNORECASE,
)


def _canonical_asin_mismatch(html: str, requested_url: str) -> tuple[str, str, str] | None:
    """`(requested_asin, canonical_href, canonical_asin)` when the page's
    own canonical link disagrees with the ASIN that was requested — a
    silent wrong-product response (F26). `None` when there's nothing to
    compare (no canonical tag at all — every synthetic unit-test fixture
    has none — or either side doesn't parse to a 10-char ASIN, e.g. a
    979-prefix ISBN-13 book identifier has no ASIN form at all) or when
    they agree. Never raises.
    """
    m = _CANONICAL_LINK_RE.search(html)
    if m is None:
        return None
    canonical_href = m.group(1)
    requested_match = _REQUESTED_URL_ASIN_RE.search(requested_url)
    if requested_match is None:
        return None
    requested_asin = requested_match.group(1).upper()
    try:
        canonical_asin = to_asin(canonical_href)
    except ValueError:
        return None
    if requested_asin == canonical_asin:
        return None
    return requested_asin, canonical_href, canonical_asin


class AmazonUKInlineSource(BrowserSessionMixin, InlineSource):
    """Amazon UK scraper backed by headless Chromium (Playwright).

    Renders both the dp and the offer-listing pages on every fetch and
    merges the offers, deduping rows that appear on both. Books-only —
    `AmazonUKProductInlineSource` handles products. Both share the lower-
    level `_fetch_offers_for_asin` helper so DOM contract changes only need
    to land in one place. Browser lifecycle comes from `BrowserSessionMixin`
    — the scheduler calls `prepare()`/`cleanup()` around a run; `fetch()`
    reuses the context `prepare()` opened rather than launching its own.
    """

    def __init__(
        self,
        name: str = "amazon",
        region: str = "UK",
        timeout_s: float = 30.0,
    ) -> None:
        if region.upper() != "UK":
            raise ValueError(
                f"AmazonUKInlineSource only supports region='UK' at MVP, got {region!r}"
            )
        self.name = name
        self.region = region
        self.timeout_s = timeout_s

    def dp_url(self, isbn13: str) -> str:
        return amazon_uk_dp_url(isbn13)

    def offer_listing_url(self, isbn13: str) -> str:
        return _offer_listing_url_for_asin(asin_for_amazon_uk(isbn13))

    async def fetch(self, item: TrackedItem) -> list[ObservationCandidate]:
        # Books-only source. Defence in depth: scheduler already filters by
        # item_kinds, but a misconfigured Source instance is the kind of
        # thing we'd rather hit hard than silently no-op.
        assert isinstance(item, Book), f"{self.name} only handles books"
        assert self._context is not None, (
            f"{self.name}.prepare() must run before fetch()"
        )
        # Books always track every condition Amazon publishes — the used
        # market is the whole point of the book pipeline.
        return await _fetch_offers_for_asin(
            asin_for_amazon_uk(item.isbn13),
            context=self._context,
            source_name=self.name,
            timeout_s=self.timeout_s,
            track_used=True,
        )

    async def _render_page(
        self,
        context,
        url: str,
        *,
        wait_selector: str,
        wait_ms: int,
    ) -> str:
        """Open a page in `context`, navigate, return HTML after wait.

        Kept as an instance method only because two tests poke it
        directly; the AmazonProductSource uses the module-level
        `_render_amazon_page` helper. Both call sites share the same
        Playwright logic; do not let the two implementations drift.
        """
        return await _render_amazon_page(
            context,
            url,
            wait_selector=wait_selector,
            wait_ms=wait_ms,
            navigation_timeout_s=self.timeout_s,
            source_name=self.name,
        )


def _offer_listing_url_for_asin(asin: str) -> str:
    return f"https://www.amazon.co.uk/gp/offer-listing/{asin}?condition=all"


async def _render_amazon_page(
    context: BrowserContext,
    url: str,
    *,
    wait_selector: str,
    wait_ms: int,
    navigation_timeout_s: float,
    source_name: str,
) -> str:
    """Open `url` in a Playwright `context`, wait for `wait_selector`, return
    rendered HTML. Selector-timeout is fine — capture content and let the
    parser decide whether to fall back or report empty. Raises SourceError
    on navigation timeout, a persistent bot-challenge marker, or a canonical
    ASIN mismatch (F26 — Amazon silently serving a different product's
    page); both of the latter also dump the HTML via `write_debug_capture`
    (T1.5) so the actual page is inspectable, not just the SourceError
    message.
    """
    page = await context.new_page()
    try:
        await page.goto(
            url, wait_until="domcontentloaded", timeout=navigation_timeout_s * 1000
        )
    except PlaywrightTimeoutError as e:
        raise SourceError(source_name, f"navigation timed out: {e}") from e
    try:
        await page.wait_for_selector(wait_selector, timeout=wait_ms, state="attached")
    except PlaywrightTimeoutError:
        pass
    html = await page.content()
    for marker in BOT_MARKERS:
        if marker in html:
            write_debug_capture(source_name, html)
            raise SourceError(
                source_name,
                "Amazon bot-protection challenge persisted; "
                "Playwright was unable to clear it",
            )

    mismatch = _canonical_asin_mismatch(html, url)
    if mismatch is not None:
        requested_asin, canonical_href, canonical_asin = mismatch
        write_debug_capture(source_name, html)
        raise SourceError(
            source_name,
            f"canonical URL mismatch: requested {url!r} (ASIN {requested_asin}) "
            f"but the page's own canonical link is {canonical_href!r} "
            f"(ASIN {canonical_asin}) — Amazon served a different product's page",
        )
    return html


async def _fetch_offers_for_asin(
    asin: str,
    *,
    context: BrowserContext,
    source_name: str,
    timeout_s: float,
    track_used: bool,
) -> list[ObservationCandidate]:
    """Render Amazon UK dp + offer-listing for `asin` in `context`, merge + dedup.

    `context` is the source's shared `BrowserSession` context (opened once
    per scheduler run by `BrowserSessionMixin.prepare()`), not a per-call
    browser launch — every item fetched by this source run reuses it.

    `track_used=False` filters out non-NEW conditions before merging — used
    by `AmazonUKProductInlineSource` because most non-book products have no
    meaningful used market on Amazon. Books always pass `True`.

    Shared between the book source and the product source so the Playwright
    dance, bot-marker handling, and DOM contract live in one place.
    """
    dp_url = f"https://www.amazon.co.uk/dp/{asin}"
    offer_url = _offer_listing_url_for_asin(asin)
    dp_html = await _render_amazon_page(
        context,
        dp_url,
        wait_selector=(
            "#corePriceDisplay_desktop_feature_div, "
            "#corePrice_feature_div, "
            ".a-price .a-offscreen"
        ),
        # Buy-box renders fast — cap the wait so a buy-box-less
        # listing doesn't burn the full Playwright timeout.
        wait_ms=min(10_000, int(timeout_s * 1000)),
        navigation_timeout_s=timeout_s,
        source_name=source_name,
    )
    dp_offers = parse_dp(dp_html, dp_url, source_name=source_name)
    offer_html = await _render_amazon_page(
        context,
        offer_url,
        wait_selector="#aod-offer-list, .olpOfferList",
        wait_ms=int(timeout_s * 1000),
        navigation_timeout_s=timeout_s,
        source_name=source_name,
    )
    offer_listing_offers = parse_offer_listing(
        offer_html, offer_url, source_name=source_name,
    )
    merged = _merge_offers([*dp_offers, *offer_listing_offers])
    if not track_used:
        merged = [o for o in merged if o.condition == Condition.NEW]
    return merged


class AmazonUKProductInlineSource(BrowserSessionMixin, InlineSource):
    """Amazon UK scraper for non-book products. ASIN comes straight from
    `Product.asin` (no ISBN conversion). Honours `Product.track_used` for
    the per-row used-market opt-in. Browser lifecycle from
    `BrowserSessionMixin` — see `AmazonUKInlineSource`.
    """

    name = "amazon_uk_product"
    item_kinds = frozenset({ItemKind.PRODUCT})

    def __init__(
        self,
        name: str = "amazon_uk_product",
        region: str = "UK",
        timeout_s: float = 30.0,
    ) -> None:
        if region.upper() != "UK":
            raise ValueError(
                f"AmazonUKProductInlineSource only supports region='UK' at MVP, got {region!r}"
            )
        self.name = name
        self.region = region
        self.timeout_s = timeout_s

    def dp_url(self, asin: str) -> str:
        return amazon_uk_product_dp_url(asin)

    def offer_listing_url(self, asin: str) -> str:
        return _offer_listing_url_for_asin(asin)

    async def fetch(self, item: TrackedItem) -> list[ObservationCandidate]:
        assert isinstance(item, Product), f"{self.name} only handles products"
        assert self._context is not None, (
            f"{self.name}.prepare() must run before fetch()"
        )
        return await _fetch_offers_for_asin(
            item.asin,
            context=self._context,
            source_name=self.name,
            timeout_s=self.timeout_s,
            track_used=item.track_used,
        )


def _normalize_seller(seller: str | None) -> str:
    """Case- and whitespace-insensitive seller key.

    Uses `.lower()` (not `.casefold()`) to stay in lockstep with SQLite's
    ASCII-only `LOWER()` used by the persistence-layer match in
    `scheduler._persist`. For Amazon UK seller names (all ASCII in
    practice) lower() == casefold(), so the choice only matters when
    paranoid Unicode parity comes up — and SQLite's LOWER is the
    constraint that pins the choice.
    """
    return (seller or "").strip().lower()


def _merge_offers(offers: list[ObservationCandidate]) -> list[ObservationCandidate]:
    """Merge dp + offer-listing offers, deduping rows that describe the same offer.

    Match on (normalized seller, condition, price_minor). Shipping is left
    out of the key because the dp delivery block and the offer-listing
    `#aod-offer-shipping` line can disagree representationally for the
    same buy-box offer.

    Two DIFFERENT reasons a duplicate can disagree on shipping, resolved
    oppositely (S8):

    - One side is `None` because it never observed anything at all (the dp
      slot hydration-skeletoned) and the other has a genuine non-zero
      charge (e.g. 280). The charge is strictly more informative than no
      data — it wins, unchanged since before T2.5.
    - One side is `None` because T2.5/D33/D35 positively confirmed the
      promise is conditional, and the other is exactly `0`. Since T2.5,
      `0` disagreeing with `None` is NOT "a known value beats no
      information" — the `0` might itself just be a miss (that render's
      layout lacked the attribute or qualifying text the other one had),
      and the `None` is the more recently-earned, positive finding.
      Preferring the concrete `0` here would silently discard exactly the
      finding T2.5/D33/D35 exist to surface. `None` wins in this specific
      case — never a non-zero concrete value, only `0`, since a real paid
      charge is never something T2.5/D33/D35 would have nulled out.
    """
    by_key: dict[tuple[str, str, int], ObservationCandidate] = {}
    for o in offers:
        key = (_normalize_seller(o.seller), o.condition, o.price_minor)
        existing = by_key.get(key)
        if existing is None:
            by_key[key] = o
            continue
        e_ship, o_ship = existing.shipping_minor, o.shipping_minor
        if e_ship is None and o_ship is not None and o_ship != 0:
            by_key[key] = o
        elif e_ship == 0 and o_ship is None:
            by_key[key] = o
    return list(by_key.values())


_FREE_DELIVERY_RE = re.compile(r"\bFREE\s+delivery\b", re.IGNORECASE)
# Matches "£2.80 delivery" / "£ 2.80 delivery"; intentionally not symmetric
# with "delivery £2.80" because no real Amazon UK dp markup uses that order
# (verified against live captures 2026-05-15). Add the reverse if we ever see it.
_PAID_DELIVERY_RE = re.compile(
    r"£\s*(\d+(?:\.\d{1,2})?)\s*delivery", re.IGNORECASE
)
# Containers Amazon UK uses to surface the buy-box delivery line. In order of
# preference: the static MIR slot (always populated when present), then the
# legacy deliveryBlockMessage, then the dynamic widget that A/B-tests render
# instead of MIR. We return on the first one that has actual text — empty
# nodes are skipped because Amazon ships skeleton markup it hydrates later.
_DELIVERY_BLOCK_SELECTORS: tuple[str, ...] = (
    "#mir-layout-DELIVERY_BLOCK-slot-PRIMARY_DELIVERY_MESSAGE_LARGE",
    "#deliveryBlockMessage",
    "#dynamicDeliveryMessage",
)


def _find_dp_delivery_block(tree: HTMLParser) -> Node | None:
    """The ONE delivery block `_extract_dp_shipping_minor`,
    `_extract_dp_delivery_text` and `_extract_dp_delivery_condition_attrs`
    all read from (S6 fix).

    Before this, the three scanned `_DELIVERY_BLOCK_SELECTORS`
    independently with different "which block wins" rules:
    `_extract_dp_shipping_minor` skipped a non-empty block that didn't
    parse as FREE or a £X.XX charge and kept looking, while
    `_extract_dp_delivery_text` returned the first non-empty block
    regardless of whether it matched anything — a documented invariant
    ("the captured text always corresponds to the block that produced
    shipping_minor") that could be, and on a synthetic two-block page
    reproducibly was, false: `_extract_dp_shipping_minor` could return a
    value from block 2 while `_extract_dp_delivery_text` returned block
    1's unrelated text, silently blinding the conditional-delivery rule
    to whatever qualifier actually applied. Verified before this fix that
    every capture on file (real and synthetic) already had all three
    functions agreeing on which block to use, so unifying them here does
    not change any existing parse result — it only replaces "probably
    agrees" with "provably the same node".

    Selection rule is `_extract_dp_shipping_minor`'s original, stricter
    one — first block that is non-empty AND recognisably parses as either
    a free or a paid promise — since `delivery_text` and the D35 attribute
    pair exist specifically to describe whatever produced `shipping_minor`,
    not to independently guess at "the first block with any text in it".
    F-B9 changed how `_extract_dp_shipping_minor` turns that block's text
    into a value (it now delegates to `_parse_delivery_text`) but not this
    gate — `_FREE_DELIVERY_RE`/`_PAID_DELIVERY_RE` here are still only
    deciding "does this block look like a delivery promise at all", which
    stays a coarser check than the value parser.
    """
    for sel in _DELIVERY_BLOCK_SELECTORS:
        node = tree.css_first(sel)
        if node is None:
            continue
        text = (node.text() or "").strip()
        if not text:
            continue
        if _FREE_DELIVERY_RE.search(text) or _PAID_DELIVERY_RE.search(text):
            return node
    return None


def _extract_dp_shipping_minor(tree: HTMLParser) -> int | None:
    """Pull the buy-box delivery cost in pence from `tree`, or None.

    Returns 0 when the delivery line says "FREE delivery", an integer pence
    value when it says "£X.XX delivery", and None when no populated delivery
    block is present — None means "we didn't observe shipping" rather than
    "free", so downstream can choose to fall back honestly.

    F-B9: delegates to `_parse_delivery_text` (below), the same parser the
    AOD path (`_extract_shipping_minor`) uses, instead of keeping a second,
    divergent free-vs-paid precedence rule. This function used to check
    "FREE delivery" before the £-amount, so a combined sentence like
    "£3.49 delivery. Free delivery over £25." collapsed to 0 here even
    though D36 ratifies numeric-first precedence (349) specifically to
    stop a real charge being masked by a later conditional promise on the
    same line — the AOD path already implemented that correctly.
    `_find_dp_delivery_block` still gates which block counts as the
    delivery block using the stricter `_FREE_DELIVERY_RE`/`_PAID_DELIVERY_
    RE` pair (unchanged, and still needed for that skeleton-markup check);
    only the value extracted FROM that block now goes through
    `_parse_delivery_text` so both paths agree on precedence. Verified
    against every dp fixture on file (real and synthetic) that this
    produces the same result as before on all of them — the ordering only
    differs on a sentence containing both a concrete charge and a
    threshold promise together, which no fixture currently exercises.
    """
    node = _find_dp_delivery_block(tree)
    if node is None:
        return None
    text = (node.text() or "").strip()
    return _parse_delivery_text(text)


def _extract_dp_delivery_text(tree: HTMLParser) -> str | None:
    """The buy-box delivery line's raw text (T1.5 diagnostic capture),
    independent of `_extract_dp_shipping_minor`'s parse of it into pence.
    Reads the SAME block `_extract_dp_shipping_minor` used (S6 fix — see
    `_find_dp_delivery_block`), so the captured text is guaranteed, not
    just expected, to correspond to whatever produced `shipping_minor`.

    Whitespace is collapsed to single spaces (`_extract_offer_seller`'s
    existing convention for the same reason) — not truncated, not
    summarised, every word Amazon rendered is kept — because Amazon's
    markup line-wraps this block across several indented lines, and a
    future conditional-promo substring match (e.g. "on your first order")
    must not silently miss a phrase that happens to wrap mid-sentence in
    the raw HTML.
    """
    node = _find_dp_delivery_block(tree)
    if node is None:
        return None
    text = _node_text_collapsed(node)
    return text or None


# D35: Amazon renders a machine-readable verdict inside the exact element
# `_extract_dp_shipping_minor`/`_extract_offer_delivery_text` already read —
# `data-csa-c-mir-sub-type="CONDITIONALLY_FREE"` plus a free-text
# `data-csa-c-delivery-condition="<why>"` — that the codebase ignored
# entirely until now. Verified across every committed capture: 10 nodes
# read `CONDITIONALLY_FREE` (the 8 first-order + 2 spend-threshold rows
# D20/D33 already found by English wording) and 47 read empty/absent,
# perfect agreement with ground truth and with the regex markers below.
# `data-csa-c-mir-sub-type` (a controlled-vocabulary status field) is used
# as the key rather than `data-csa-c-delivery-condition` (free descriptive
# text): a status enum is the more reliable signal for a boolean decision
# because it doesn't depend on Amazon also having populated human-readable
# text alongside it. The condition text is kept only for the diagnostic
# log line below, not for the decision itself.
#
# Caveat carried forward from the review that found this: 10 captures is
# the whole evidence base, so `CONDITIONALLY_FREE` is not assumed to be
# the only non-empty value `mir-sub-type` can take — this checks for that
# exact string, not "any non-empty value".
def _extract_dp_delivery_condition_attrs(tree: HTMLParser) -> tuple[bool | None, str | None]:
    """`(attribute_says_conditional, raw_condition_text)` for the dp buy-box.

    Reads the SAME block `_extract_dp_shipping_minor`/`_extract_dp_delivery_
    text` used (S6 fix — see `_find_dp_delivery_block`), so this can never
    disagree with them about which physical block the row's delivery data
    lives in. `None` means the attribute itself is absent within that block
    (a layout Amazon hasn't tagged this way at all, e.g. the synthetic test
    fixtures, or no delivery block was found at all) — the caller falls
    back to the English-marker regex in that case rather than treating
    `None` as "unconditional".
    """
    block = _find_dp_delivery_block(tree)
    if block is None:
        return None, None
    node = block.css_first("[data-csa-c-mir-sub-type]")
    if node is None:
        return None, None
    sub_type = (node.attributes.get("data-csa-c-mir-sub-type") or "").strip()
    condition_text = (
        node.attributes.get("data-csa-c-delivery-condition") or ""
    ).strip() or None
    return sub_type == "CONDITIONALLY_FREE", condition_text


def _extract_offer_delivery_condition_attrs(row: Node) -> tuple[bool | None, str | None]:
    """D35 equivalent of `_extract_dp_delivery_condition_attrs` for an AOD
    row — reads the same `[data-csa-c-delivery-price]` node
    `_extract_shipping_minor` already finds, so this can never disagree
    with that function about *which* node the row's delivery data lives in
    (unlike the dp side's S6 caveat, there is only one such node per row on
    every capture on file)."""
    node = row.css_first("[data-csa-c-delivery-price]")
    if node is None or "data-csa-c-mir-sub-type" not in node.attributes:
        return None, None
    # selectolax normalises `attr=""` to `None` via `.get()`, so `or ""` is
    # needed to tell "present but empty" (a real "not conditional" verdict)
    # apart from a lookup failure — the presence check above already ruled
    # out "genuinely absent".
    sub_type = (node.attributes.get("data-csa-c-mir-sub-type") or "").strip()
    condition_text = (node.attributes.get("data-csa-c-delivery-condition") or "").strip() or None
    return sub_type == "CONDITIONALLY_FREE", condition_text


# T2.5 (D20) + D33: the project's worst data bug (finding F1). A visitor
# gets shown one of Amazon's conditional "FREE delivery" promises — a price
# this particular order would not actually qualify for — and the old parser
# recorded it as shipping_minor=0 indistinguishably from a genuine
# free-shipping offer. Two markers are evidenced, both from real captures,
# not guessed:
#
# 1. First-order promo: "on your first order" — the wave0 probe's capture
#    of one ASIN, and `tests/fixtures/amazon/products/B0F3NVWM37-uk-aod-
#    2026-09-04.html` (8 of 10 real AOD rows), both reading verbatim `FREE
#    delivery <dates> on your first order to UK or Ireland`.
# 2. Spend-threshold promo (D33): `tests/fixtures/amazon/products/
#    B0CYT8WL1G-uk-dp-2026-09-04.html` reads verbatim `FREE delivery
#    Tuesday, 8 September on orders dispatched by Amazon over £35` — a
#    single sub-threshold item does not qualify, so this is the same
#    defect class as F1, found incidentally while covering that fixture
#    for a different task (T4.2) and confirmed as a real bug (D33), not
#    folded in silently.
#
# The rule keys on CONDITIONALITY, not on any specific threshold value —
# matching literal "£35" would be exactly the kind of guess this task
# exists to avoid, and Q2 (whether the real threshold is £35 general or
# £10 of books, or varies by category) stays open and not load-bearing:
# `over £<any amount>` is itself the evidence of a condition the scraper
# cannot verify for a single item, regardless of what the amount is.
#
# The plan also guessed at "with Prime" as a further conditional marker;
# it doesn't appear in any capture on file as an actual delivery promise —
# only ever in unrelated product-variant JSON
# ("PRIME_SAVINGS_UPSELL":"With Prime"), never near a delivery line. Widen
# this set only against a new capture, per D20's own revisit trigger.
#
# D35 demoted this regex from primary detection to FALLBACK: an adversarial
# review found Amazon ships its own machine-readable verdict
# (`data-csa-c-mir-sub-type="CONDITIONALLY_FREE"`) inside the very node
# these functions already read, in perfect agreement with both markers
# below across every capture on file — see
# `_extract_dp_delivery_condition_attrs` / `_extract_offer_delivery_
# condition_attrs` and `_conditional_free_shipping_to_unknown`. This regex
# stays as the second layer precisely because that attribute is
# undocumented and Amazon can drop it silently — D20's own evidence (8 of
# 9 rows wrongly free) is what trusting only one detection layer costs.
_CONDITIONAL_DELIVERY_RE = re.compile(
    r"on your first order|over\s*£\s*\d",
    re.IGNORECASE,
)


def _conditional_free_shipping_to_unknown(
    shipping_minor: int | None,
    delivery_text: str | None,
    *,
    attribute_conditional: bool | None = None,
    attribute_condition_text: str | None = None,
    source_name: str = "amazon",
) -> int | None:
    """T2.5/D33/D35: when `shipping_minor` reads as free (0) but the promise
    is conditional, the shipping cost is unknown, not zero — return `None`
    so downstream (`effective_shipping`) substitutes the cascade estimate
    and reports `is_estimate=True` instead of ranking the offer on a price
    the buyer won't actually get. A genuinely unconditional "FREE delivery"
    is untouched and stays 0; a paid delivery charge is untouched
    regardless of wording, since this only ever fires on
    `shipping_minor == 0`.

    D35: `attribute_conditional` — Amazon's own `data-csa-c-mir-sub-type`
    verdict (`None` when that attribute isn't present on this page's
    layout at all, e.g. the synthetic test fixtures) — and the
    `delivery_text` regex (D20/D33) are two independent layers over the
    SAME question, and either one flagging "conditional" is enough to
    convert the free-looking shipping to unknown: `conditional =
    bool(attribute_conditional) or text_conditional`. This is F-B6's fix —
    an earlier version let the attribute's verdict override the text
    layer outright, which meant a single new `mir-sub-type` value this
    code doesn't yet recognise (only `CONDITIONALLY_FREE` is evidenced;
    see the module comment above) would silently reinstate F1 even though
    the text still read a first-order/spend-threshold promise verbatim.
    D38's risk asymmetry (recording `0` under-states delivered cost, the
    exact harm class this project exists to close; recording `None` only
    adds a cascade estimate) means the fallback must be able to RAISE the
    verdict to conditional on its own, not just be consulted when the
    attribute is silent. A disagreement between the two is still logged
    with the raw `data-csa-c-delivery-condition` text (D35's load-bearing
    diagnostic: same reasoning as `condition_normalizers.grade_unmapped`,
    D26 — the log line is what makes drift visible) whenever the attribute
    is present, even though the disagreement no longer changes the
    outcome by itself. The English markers are NOT retired: the attribute
    is undocumented and Amazon can drop it without notice, and D20's own
    evidence (8 of 9 rows wrongly free) is what a silent detection failure
    costs.
    """
    if shipping_minor != 0:
        return shipping_minor

    text_conditional = bool(
        delivery_text is not None and _CONDITIONAL_DELIVERY_RE.search(delivery_text)
    )
    conditional = bool(attribute_conditional) or text_conditional

    if attribute_conditional is not None and attribute_conditional != text_conditional:
        log.warning(
            "amazon.conditional_delivery.layers_disagree",
            source=source_name,
            attribute_conditional=attribute_conditional,
            text_conditional=text_conditional,
            delivery_condition=attribute_condition_text,
            delivery_text=delivery_text,
        )
    return None if conditional else shipping_minor


def parse_dp(
    html: str,
    fallback_url: str,
    *,
    source_name: str = "amazon",
) -> list[ObservationCandidate]:
    """Parse Amazon UK dp-page HTML into ObservationCandidates.

    Returns at most one offer (the buy-box). Empty list means no usable
    price was found — the caller should fall back to the offer-listing page.

    `source_name` is used in the SourceError message only — both book and
    product sources call this helper; default `"amazon"` keeps existing
    tests that don't pass the kwarg passing.

    Price extraction tries two paths in order:
      1. selectolax CSS scrape of `.a-price .a-offscreen` under the
         corePriceDisplay scope (cheap, works on simpler pages).
      2. Regex against `"priceAmount":<float>` in the raw HTML (slower
         but robust against Amazon's hydration shuffle that moves the
         visible buy-box element out of the corePriceDisplay subtree).
    """
    if not html:
        return []
    tree = HTMLParser(html)

    price_minor: int | None = None
    for sel in (
        "#corePriceDisplay_desktop_feature_div",
        "#corePrice_feature_div",
        "#priceblock_ourprice",
        "#price",
    ):
        scope = tree.css_first(sel)
        if scope is not None:
            price_minor = _extract_price_minor(scope)
            if price_minor is not None:
                break

    if price_minor is None:
        price_minor = _extract_priceamount_minor(tree, html)
    if price_minor is None:
        # No buy-box price found. Distinguish "real Amazon dp page with no
        # buy-box / unavailable" (return []) from "Amazon served something
        # we don't recognise" (raise) — see `_DP_PAGE_MARKERS` rationale.
        if not _matches_any_selector(tree, _DP_PAGE_MARKERS):
            write_debug_capture(source_name, html)
            raise SourceError(
                source_name,
                "dp page did not match any known Amazon UK layout "
                "(no buy-box price, no #dp-container or #productTitle); "
                "treating as anti-bot variant rather than reporting 0 offers",
            )
        return []

    seller = _extract_dp_seller(tree)
    shipping_minor = _extract_dp_shipping_minor(tree)
    delivery_text = _extract_dp_delivery_text(tree)
    attribute_conditional, attribute_condition_text = _extract_dp_delivery_condition_attrs(tree)
    shipping_minor = _conditional_free_shipping_to_unknown(
        shipping_minor,
        delivery_text,
        attribute_conditional=attribute_conditional,
        attribute_condition_text=attribute_condition_text,
        source_name=source_name,
    )
    condition = _extract_dp_condition(tree, seller, source_name=source_name)
    item_title = _extract_item_title(tree)
    item_image_url = _extract_item_image_url(tree)

    return [
        ObservationCandidate(
            seller=seller,
            condition=condition,
            price_minor=price_minor,
            shipping_minor=shipping_minor,
            delivery_text=delivery_text,
            currency="GBP",
            url=fallback_url,
            item_title=item_title,
            item_image_url=item_image_url,
        )
    ]


# T4.1: title/image for a still-PENDING product (scheduler._persist resolves
# it off whichever candidate carries a non-None item_title — dp only, an AOD
# row never sets these). Selectors matched from metadata.py's
# `_AMAZON_TITLE_SELECTORS` / `_AMAZON_COVER_SELECTORS` (the already-proven
# interactive asin-lookup path), not imported from there: metadata.py
# already imports `BOT_MARKERS` from this module, so importing back would be
# circular.
_ITEM_TITLE_SELECTORS = ("#productTitle",)
_ITEM_IMAGE_SELECTORS = ("#landingImage", "#imgBlkFront", "#ebooksImgBlkFront")


def _extract_item_title(tree: HTMLParser) -> str | None:
    for sel in _ITEM_TITLE_SELECTORS:
        node = tree.css_first(sel)
        if node is not None:
            text = _node_text(node)
            if text:
                return text
    return None


def _extract_item_image_url(tree: HTMLParser) -> str | None:
    for sel in _ITEM_IMAGE_SELECTORS:
        node = tree.css_first(sel)
        if node is not None:
            src = node.attributes.get("src") or node.attributes.get("data-old-hires")
            if src:
                return src
    return None


def _extract_priceamount_minor(tree: HTMLParser, html: str) -> int | None:
    """Return the buy-box `priceAmount` in pence, or None.

    Scoping rationale: Amazon's pricing service serializes the buy-box
    price into a `twister-plus-buying-options-price-data` div as JSON
    keyed by `desktop_buybox_group_<N>`. Searching the FULL page HTML
    with the priceAmount regex used to work by happy accident — the
    buy-box JSON happened to appear before any other `"priceAmount"`
    occurrence on every captured page. But Amazon also embeds priceAmount
    in unrelated rails (frequently-bought-together, recommended titles,
    seller-storefront cards) and there's no guarantee the buy-box block
    stays first when Amazon reshuffles the DOM. Scope to the buy-box
    data div when present so the regex can't drift onto an unrelated
    price. If the div isn't found (older layout, A/B variant), fall
    back to the page-wide search rather than silently dropping the
    fallback price path entirely.
    """
    scope = tree.css_first("div.twister-plus-buying-options-price-data")
    haystack = scope.text() if scope is not None else html
    m = _PRICE_AMOUNT_RE.search(haystack)
    if m is None:
        return None
    try:
        return round(float(m.group(1)) * 100)
    except ValueError:
        return None


def parse_offer_listing(
    html: str,
    fallback_url: str,
    *,
    source_name: str = "amazon",
) -> list[ObservationCandidate]:
    """Parse Amazon UK offer-listing-page HTML into ObservationCandidates.

    `source_name` is used in the SourceError message only — both book and
    product sources call this helper; default `"amazon"` keeps existing
    tests that don't pass the kwarg passing.
    """
    if not html:
        return []
    tree = HTMLParser(html)

    # Modern AOD layout: #aod-offer rows under #aod-offer-list.
    # Legacy fallback: .olpOffer rows.
    rows = tree.css("#aod-offer-list #aod-offer")
    if not rows:
        rows = tree.css(".olpOffer")

    offers: list[ObservationCandidate] = []
    for row in rows:
        offer = _parse_offer_row(row, fallback_url, source_name=source_name)
        if offer is not None:
            offers.append(offer)
    if (
        not offers
        and not _matches_any_selector(tree, _OFFER_LISTING_PAGE_MARKERS)
        and not _matches_any_selector(tree, _UNAVAILABLE_PAGE_MARKERS)
    ):
        # No rows found AND no recognised offer-listing container AND no
        # "currently unavailable" marker either — Amazon almost certainly
        # served an anti-bot or unrelated variant. Raise rather than report
        # 0; see `_OFFER_LISTING_PAGE_MARKERS` / `_UNAVAILABLE_PAGE_MARKERS`
        # rationale.
        write_debug_capture(source_name, html)
        raise SourceError(
            source_name,
            "offer-listing page did not match any known Amazon UK layout "
            "(no #aod-container / #aod-offer-list / #olpOfferList / "
            "#outOfStockBuyBox_feature_div); "
            "treating as anti-bot variant rather than reporting 0 offers",
        )
    return offers


def _parse_offer_row(
    row: Node, fallback_url: str, *, source_name: str = "amazon"
) -> ObservationCandidate | None:
    price_minor = _extract_price_minor(row)
    if price_minor is None:
        return None

    shipping_minor = _extract_shipping_minor(row)
    delivery_text = _extract_offer_delivery_text(row)
    attribute_conditional, attribute_condition_text = _extract_offer_delivery_condition_attrs(row)
    shipping_minor = _conditional_free_shipping_to_unknown(
        shipping_minor,
        delivery_text,
        attribute_conditional=attribute_conditional,
        attribute_condition_text=attribute_condition_text,
        source_name=source_name,
    )
    condition = _extract_condition(row, source_name=source_name)
    seller = _extract_offer_seller(row)

    # Clickout: the offer-listing page (`fallback_url`), NOT the seller's
    # storefront. Amazon's AOD rows carry no stable per-offer deep link — the
    # only anchors are the shipping-help page, the seller-rating tooltip, and
    # the seller's storefront. The storefront is a dead end for the buyer:
    # Amazon Resale's "storefront" is the generic `/Amazon-Warehouse-Deals/b`
    # category page (no sign of the actual book), and a marketplace seller's
    # is their whole catalogue. The offer-listing page shows THIS offer in
    # context, sorted with the others by price — the page a user actually
    # wants when they click "Open offer".
    return ObservationCandidate(
        seller=seller,
        condition=condition,
        price_minor=price_minor,
        shipping_minor=shipping_minor,
        delivery_text=delivery_text,
        currency="GBP",
        url=fallback_url,
    )


# Class tokens that mark a price span as a strike-through RRP rather than
# the actual offer price. `basisPrice` is the legacy hook; the modern apex
# pricing template uses `apex-basisprice-value` for the inner `<span>` and
# `centralizedApexBasisPriceCSS` for its container. `apb-price-was` and
# `a-text-strike` cover older A/B variants.
_STRIKE_THROUGH_ANCESTORS: tuple[str, ...] = (
    "basisPrice",
    "apex-basisprice-value",
    "centralizedApexBasisPriceCSS",
    "apb-price-was",
    "a-text-strike",
)


def _extract_price_minor(scope: Node) -> int | None:
    """Pull the offer price in pence from `scope`.

    Two paths, tried in order:

    1. `.apex-pricetopay-accessibility-label` — modern apex pricing
       template renders the offer price as plain text inside an
       `aok-offscreen` span carrying this class. It sits as a SIBLING of
       `.a-price` (not a child), so the legacy `.a-price .a-offscreen`
       scan below cannot reach it. Real Amazon UK offer-listing rows ship
       the `.a-offscreen` inside `.a-price` empty for the offer price —
       the visible price is assembled from `.a-price-whole` /
       `.a-price-fraction` under `aria-hidden=true` — which is why a
       parser that only walks `.a-price .a-offscreen` ends up picking up
       the strike-through RRP instead. Reading the pricetopay
       accessibility label fixes this.

    2. Fallback: `.a-price .a-offscreen` scan, used by the synthetic
       fixtures and older AOD templates. Skip strike-through RRPs via
       `_STRIKE_THROUGH_ANCESTORS`.
    """
    for label in scope.css(".apex-pricetopay-accessibility-label"):
        if _ancestor_has_class(label, _STRIKE_THROUGH_ANCESTORS):
            continue
        minor = _parse_gbp_to_minor((label.text() or "").strip())
        if minor is not None:
            return minor
    for off in scope.css(".a-price .a-offscreen"):
        if _ancestor_has_class(off, _STRIKE_THROUGH_ANCESTORS):
            continue
        minor = _parse_gbp_to_minor((off.text() or "").strip())
        if minor is not None:
            return minor
    return None


def _ancestor_has_class(node: Node, class_tokens: tuple[str, ...]) -> bool:
    """True if any ancestor of `node` has one of the given class tokens."""
    cur = node.parent
    while cur is not None:
        attrs = cur.attributes or {}
        classes = (attrs.get("class") or "").split()
        if any(t in classes for t in class_tokens):
            return True
        cur = cur.parent
    return False


def _parse_gbp_to_minor(text: str) -> int | None:
    """Parse "£7.99" / "&pound;7.99" / "7.99" → 799 (pence)."""
    if not text:
        return None
    m = _PRICE_NUMERIC_RE.search(text)
    if m is None:
        return None
    try:
        return round(float(m.group(1)) * 100)
    except ValueError:
        return None


# Restrict to 0-2 decimal places and accept thousands-separator commas
# (Amazon will render postage on rare items as e.g. "£1,200.00 delivery").
# Accepting unbounded decimals would let "£12.3456" round to a £12.35
# imposter; accepting a comma-as-decimal would mis-parse "£1,200" as
# £1.20.
_DELIVERY_PRICE_GBP_RE = re.compile(
    r"£\s*([0-9]+(?:,[0-9]{3})*(?:\.[0-9]{1,2})?)"
)
# Word-boundary "free" — avoid matching "Free delivery on orders over £25"
# as zero shipping when a concrete charge is also present.
_FREE_DELIVERY_RE_DELIVERY = re.compile(r"\bfree\s+delivery\b", re.IGNORECASE)


def _is_conditional_marker_span(text: str, start: int, end: int) -> bool:
    """D36: True when `text[start:end]` overlaps a match of
    `_CONDITIONAL_DELIVERY_RE` — reused directly rather than a second
    pattern maintained in parallel, so "what counts as a conditional
    promise" only has one definition in this file. Used by
    `_parse_delivery_text` to tell a genuine "over £X" *threshold* mention
    apart from an actual "£X delivery" *charge*, which otherwise share the
    identical "£<number>" shape.

    Overlap, not containment: `_CONDITIONAL_DELIVERY_RE`'s "over £\\d"
    branch only requires a SINGLE digit after £ (it only needs to detect
    the phrase, not delimit the full amount), so its match span can end
    mid-number — e.g. "over £3" out of "over £35". A `_DELIVERY_PRICE_GBP_
    RE` match for the full "£35" would fail a strict-containment check
    against that shorter span (verified directly — this was my first,
    wrong implementation). Any overlap at all is sufficient: the only way
    the "over...£...\\d" branch matches anything is an "over" followed by a
    £-amount, which is exactly where a genuine price match would also
    land, so there is no plausible case where the two overlap without both
    describing the same £-amount.
    """
    return any(
        m.start() < end and start < m.end()
        for m in _CONDITIONAL_DELIVERY_RE.finditer(text)
    )


def _parse_delivery_text(raw: str) -> int | None:
    """Parse a delivery descriptor.

    "FREE" / "FREE delivery" → 0; "£X.XX" → pence in `X.XX`; conditional
    promises ("£3.49 delivery. Free delivery over £25.") → the concrete
    `£X.XX` value; everything else → None.

    The numeric path is tried BEFORE the free check so a conditional
    promise can never mask a real shipping charge — the prior version
    accepted any substring "free" as zero, which a "free over £X.XX"
    qualifier would silently trigger.

    D36 (S7): a £-amount is only accepted as the charge if it does NOT
    fall inside a `_CONDITIONAL_DELIVERY_RE` match — "FREE delivery ... on
    orders dispatched by Amazon over £35" used to read the £35 *threshold*
    as a £35.00 *charge* (`_DELIVERY_PRICE_GBP_RE` has no way to tell "the
    charge is £X" from "free once you spend over £X" on its own; both are
    just a £-amount to it). The precedence itself is NOT changed —
    numeric-first still exists so "£3.49 delivery. Free delivery over
    £25." correctly returns 349, not 0 — only which numeric match counts
    is now narrower. Masked in production today because
    `_extract_shipping_minor` reads the short `data-csa-c-delivery-price`
    attribute (just "FREE" or "£X.XX", never a threshold mention) before
    ever calling this function on the long human-readable sentence — this
    fix protects the fallback path for when that attribute is absent (the
    legacy `#aod-offer-shipping`-only layout, or a future template
    variant), which no capture on file currently exercises.
    """
    text = raw.strip()
    if not text:
        return None
    for m in _DELIVERY_PRICE_GBP_RE.finditer(text):
        if _is_conditional_marker_span(text, m.start(), m.end()):
            continue
        return round(float(m.group(1).replace(",", "")) * 100)
    # No concrete (non-threshold) price seen — accept "FREE" / "free
    # delivery" as genuinely-free delivery. Bare "FREE" appears in the
    # `data-csa-c-delivery-price` data attribute (controlled vocabulary).
    if text.strip().upper() == "FREE":
        return 0
    if _FREE_DELIVERY_RE_DELIVERY.search(text):
        return 0
    return None


def _extract_shipping_minor(row: Node) -> int | None:
    """Extract shipping cost in pence from an offer row; 0 for FREE.

    Modern Amazon UK AOD (live captures 2026-05-16 onward) renders the
    delivery cost as a `<span data-csa-c-delivery-price="FREE|£X.XX">`
    inside `.aod-delivery-promise`. The legacy `#aod-offer-shipping`
    selector is retained as a fallback for the synthetic fixtures still
    used by unit tests and any future template variant that brings it
    back. The `.aod-delivery-promise` text scan covers the corner case
    where the data attribute is missing but the human-readable promise
    still says "FREE delivery" or "£X.XX delivery".
    """
    sp = row.css_first("[data-csa-c-delivery-price]")
    if sp is not None:
        v = _parse_delivery_text(sp.attributes.get("data-csa-c-delivery-price") or "")
        if v is not None:
            return v
    for sel in ("#aod-offer-shipping", ".aod-delivery-promise"):
        node = row.css_first(sel)
        if node is not None:
            v = _parse_delivery_text(node.text() or "")
            if v is not None:
                return v
    return None


def _extract_offer_delivery_text(row: Node) -> str | None:
    """The offer row's raw delivery-promise text (T1.5 diagnostic capture) —
    the full human-readable promise, not the parsed pence value.

    Deliberately prefers the human-readable text nodes over the
    `data-csa-c-delivery-price` attribute `_extract_shipping_minor` reads
    first: the attribute is a short controlled value ("FREE" / "£X.XX")
    that never carries a qualifier like "on your first order to UK or
    Ireland", but `.aod-delivery-promise` / `#aod-offer-shipping`'s text
    does. A future conditional-promo rule needs that qualifier, so this
    must not collapse to the attribute's shorter value. Whitespace is
    collapsed to single spaces (not truncated or summarised — every word
    is kept) so the same qualifier can't be missed just because it
    happened to line-wrap across nested markup in the row.
    """
    for sel in ("#aod-offer-shipping", ".aod-delivery-promise"):
        node = row.css_first(sel)
        if node is not None:
            text = _node_text_collapsed(node)
            if text:
                return text
    sp = row.css_first("[data-csa-c-delivery-price]")
    if sp is not None:
        attr = (sp.attributes.get("data-csa-c-delivery-price") or "").strip()
        if attr:
            return attr
    return None


def _extract_condition(row: Node, *, source_name: str = "amazon") -> Condition:
    """Map the row's heading text ("Used - Very Good" etc.) to our enum.

    F-B8: `source_name` is forwarded to `condition_from_grade_text` so its
    `grade_unmapped` diagnostic (D26) can tell which scraper produced an
    unmapped grade instead of every call site reading `source="unspecified"`.
    """
    heading = row.css_first("#aod-offer-heading h5") or row.css_first("#aod-offer-heading")
    if heading is None:
        return "unknown"
    return condition_from_grade_text(heading.text() or "", source=source_name)


_ARIA_LABEL_SELLER_SUFFIX = ". Opens a new page"


def _extract_offer_seller(row: Node) -> str:
    """Read the seller name from an offer-listing row.

    Real Amazon UK markup uses two layouts in the soldBy block:

      - Marketplace seller: `<a aria-label="SellerName. Opens a new page"
        ...>SellerName </a>` plus a sibling `<div id="aod-offer-seller-rating">`
        carrying a rating tooltip ("Seller rating is 5 out of 5 stars").
      - Amazon-direct: no `<a>` — just `<span aria-label="Amazon. Opens a
        new page">Amazon</span>` next to the "Sold by" label span.

    Both cases attach the seller's name to an `aria-label` ending in
    "Opens a new page". Reading that attribute is the most reliable way
    to get just the seller's name without leaking the "Sold by" prefix
    or the seller-rating tooltip into the result. The element-text and
    div-text fallbacks remain for older markup variants and the
    synthetic fixtures.
    """
    for el in row.css("#aod-offer-soldBy [aria-label]"):
        label = (el.attributes.get("aria-label") or "").strip()
        if not label:
            continue
        cleaned = label.removesuffix(_ARIA_LABEL_SELLER_SUFFIX).strip()
        if cleaned:
            return cleaned
    a_text = _node_text(row.css_first("#aod-offer-soldBy a"))
    if a_text:
        return a_text
    div = row.css_first("#aod-offer-soldBy")
    if div is None:
        return "?"
    text = _node_text_collapsed(div)
    for prefix in ("Sold by:", "Sold by"):
        cleaned = text.removeprefix(prefix).strip(" : ")
        if cleaned != text:
            text = cleaned
            break
    return text or "?"


def _extract_dp_seller(tree: HTMLParser) -> str | None:
    """Buy-box seller from the dp page's `#merchant-info` block, or `None`
    if the page gives no real evidence of who it is.

    T2.7: previously defaulted to `"Amazon"` whenever `#merchant-info` was
    missing or textless — measured wrong on live markup: the Echo Dot
    fixture (`B09B96TG33-uk-dp-2026-09-04.html`, an actual Amazon-brand
    device) has zero `#merchant-info` nodes, yet the old fallback credited
    the buy-box to Amazon on no evidence at all. `None` now means "the page
    didn't tell us" — the caller (and downstream dedup/persistence, which
    already treat `seller=None` as a first-class value) handle it as
    third-party rather than silently assuming Amazon.
    """
    scope = tree.css_first("#merchant-info")
    if scope is None:
        return None
    return _node_text(scope.css_first("a")) or _node_text(scope) or None


# Amazon's own resale brands sell USED stock; their appearance in the dp
# buy-box `#merchant-info` is the most reliable signal that the displayed
# price corresponds to a Used (not New) offer. Marketplace Used buy-boxes
# do exist but are rare on Amazon UK and we conservatively report them as
# NEW until/unless a future capture forces a more nuanced detection.
#
# Exact match (not substring) — names like "Warehouse Books Ltd" or
# "Wholesale Resale Group" would otherwise be mis-classified as Used.
_AMAZON_USED_BRANDS = frozenset({"amazon resale", "amazon warehouse"})

_USED_GRADES = frozenset({Condition.USED_VG, Condition.USED_G, Condition.USED_ACCEPTABLE})


def _extract_dp_condition(
    tree: HTMLParser, seller: str | None, *, source_name: str = "amazon"
) -> Condition:
    """Decide whether the dp buy-box price refers to a New or Used copy.

    When the buy-box seller is one of Amazon's resale brands ("Amazon
    Resale" / "Amazon Warehouse"), the displayed price is for a used
    copy and the page renders a `#usedAccordionCaption_feature_div
    .a-text-bold` caption with the explicit grade ("Used – Like New",
    "Used – Very Good", etc., en-dash). `condition_from_grade_text`
    maps those to `USED_VG` / `USED_G` / `USED_ACCEPTABLE`. If the
    caption is missing or unparseable, fall back to `USED_VG` — the
    middle grade typical of Amazon Resale stock.

    All other sellers (including marketplace ones, and `None` — T2.7:
    an unattributed buy-box is never assumed to be an Amazon resale brand)
    default to `NEW`.

    F-B8: `source_name` is forwarded to `condition_from_grade_text` so its
    `grade_unmapped` diagnostic (D26) can tell which scraper produced an
    unmapped grade instead of every call site reading `source="unspecified"`.
    """
    if seller is None or seller.strip().lower() not in _AMAZON_USED_BRANDS:
        return Condition.NEW
    caption = tree.css_first("#usedAccordionCaption_feature_div .a-text-bold")
    if caption is not None:
        text = (caption.text() or "").strip()
        if text:
            grade = condition_from_grade_text(text, source=source_name)
            # Only accept used grades — if the caption text reads as NEW or
            # UNKNOWN (Amazon HTML drift, A/B test) we've already decided this
            # is a Resale row by seller-name match, so reporting NEW would be
            # contradictory. Fall through to the USED_VG default.
            if grade in _USED_GRADES:
                return grade
    return Condition.USED_VG


def _node_text_collapsed(node: Node | None) -> str:
    """Node text with internal whitespace collapsed to single spaces -- not
    truncated or summarised, every word kept. Amazon line-wraps some blocks
    (the dp delivery block, AOD row shipping/delivery text) across several
    indented lines, so a plain `.strip()` (see `_node_text`) leaves embedded
    newlines a substring match like the conditional-promo phrases can miss.
    """
    return " ".join((node.text() or "").split()) if node is not None else ""


def _node_text(node: Node | None) -> str:
    """Stripped inner text from a node, or '' if the node is None / empty."""
    return (node.text() or "").strip() if node is not None else ""
